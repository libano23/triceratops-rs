#[cfg(test)]
mod tests {
    use super::*;

    fn walk(nodes: &[Node], bad: &mut Vec<String>) {
        for n in nodes {
            match n {
                Node::Item(_, cmd) => {
                    if crate::commands::command_info(cmd).is_none() && !crate::commands::registry::is_implemented(cmd) {
                        bad.push(cmd.to_string());
                    }
                }
                Node::Sub(_, children) => walk(children, bad),
                Node::Sep => {}
            }
        }
    }

    #[test]
    fn every_menu_item_runs_a_known_command() {
        let mut bad = Vec::new();
        for tree in [FILE, EDIT, VIEW_EXTRA, CURVE, SURFACE, SUBD, SOLID, MESH, DIMENSION, TRANSFORM, TOOLS, ANALYZE, RENDER] {
            walk(tree, &mut bad);
        }
        bad.sort();
        bad.dedup();
        assert!(bad.is_empty(), "unknown menu commands: {bad:?}");
    }
}
